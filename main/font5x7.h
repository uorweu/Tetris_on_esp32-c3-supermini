/* font5x7.h - compact bitmap font shared by both display backends.
 *
 * Each glyph is 7 rows tall (plus 1 blank row = 8 bytes) and 5 pixels wide.
 * In each byte, bit4 = leftmost column ... bit0 = rightmost column.
 * Only the glyphs actually used by the UI are defined; everything else
 * renders as blank. Hand-authored so it is correct and dependency-free.
 */
#ifndef FONT5X7_H
#define FONT5X7_H

#include <stdint.h>

static inline const uint8_t *font_glyph(char c)
{
    static const uint8_t SP[8] = {0,0,0,0,0,0,0,0};

    static const uint8_t A[8] = {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11,0x00};
    static const uint8_t B[8] = {0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E,0x00};
    static const uint8_t C[8] = {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E,0x00};
    static const uint8_t D[8] = {0x1C,0x12,0x11,0x11,0x11,0x12,0x1C,0x00};
    static const uint8_t E[8] = {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F,0x00};
    static const uint8_t F[8] = {0x1F,0x10,0x10,0x1E,0x10,0x10,0x10,0x00};
    static const uint8_t G[8] = {0x0E,0x11,0x10,0x17,0x11,0x11,0x0E,0x00};
    static const uint8_t H[8] = {0x11,0x11,0x11,0x1F,0x11,0x11,0x11,0x00};
    static const uint8_t I[8] = {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E,0x00};
    static const uint8_t L[8] = {0x10,0x10,0x10,0x10,0x10,0x10,0x1F,0x00};
    static const uint8_t M[8] = {0x11,0x1B,0x15,0x15,0x11,0x11,0x11,0x00};
    static const uint8_t N[8] = {0x11,0x11,0x19,0x15,0x13,0x11,0x11,0x00};
    static const uint8_t O[8] = {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E,0x00};
    static const uint8_t P[8] = {0x1E,0x11,0x11,0x1E,0x10,0x10,0x10,0x00};
    static const uint8_t R[8] = {0x1E,0x11,0x11,0x1E,0x14,0x12,0x11,0x00};
    static const uint8_t S[8] = {0x0E,0x11,0x10,0x0E,0x01,0x11,0x0E,0x00};
    static const uint8_t T[8] = {0x1F,0x04,0x04,0x04,0x04,0x04,0x04,0x00};
    static const uint8_t U[8] = {0x11,0x11,0x11,0x11,0x11,0x11,0x0E,0x00};
    static const uint8_t V[8] = {0x11,0x11,0x11,0x11,0x11,0x0A,0x04,0x00};
    static const uint8_t W[8] = {0x11,0x11,0x11,0x15,0x15,0x1B,0x11,0x00};
    static const uint8_t X[8] = {0x11,0x11,0x0A,0x04,0x0A,0x11,0x11,0x00};
    static const uint8_t Y[8] = {0x11,0x11,0x0A,0x04,0x04,0x04,0x04,0x00};

    static const uint8_t D0[8] = {0x0E,0x13,0x15,0x15,0x19,0x11,0x0E,0x00};
    static const uint8_t D1[8] = {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E,0x00};
    static const uint8_t D2[8] = {0x0E,0x11,0x01,0x06,0x08,0x10,0x1F,0x00};
    static const uint8_t D3[8] = {0x1E,0x01,0x01,0x0E,0x01,0x01,0x1E,0x00};
    static const uint8_t D4[8] = {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02,0x00};
    static const uint8_t D5[8] = {0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E,0x00};
    static const uint8_t D6[8] = {0x0E,0x10,0x10,0x1E,0x11,0x11,0x0E,0x00};
    static const uint8_t D7[8] = {0x1F,0x01,0x02,0x04,0x08,0x08,0x08,0x00};
    static const uint8_t D8[8] = {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E,0x00};
    static const uint8_t D9[8] = {0x0E,0x11,0x11,0x0F,0x01,0x01,0x0E,0x00};

    static const uint8_t COLON[8] = {0x00,0x04,0x04,0x00,0x04,0x04,0x00,0x00};
    static const uint8_t DOT[8]   = {0x00,0x00,0x00,0x00,0x00,0x04,0x04,0x00};
    static const uint8_t DASH[8]  = {0x00,0x00,0x00,0x1F,0x00,0x00,0x00,0x00};
    static const uint8_t SLASH[8] = {0x01,0x02,0x02,0x04,0x08,0x08,0x10,0x00};

    switch (c) {
        case 'A': return A; case 'B': return B; case 'C': return C;
        case 'D': return D; case 'E': return E; case 'F': return F;
        case 'G': return G; case 'H': return H; case 'I': return I;
        case 'L': return L; case 'M': return M; case 'N': return N;
        case 'O': return O; case 'P': return P; case 'R': return R;
        case 'S': return S; case 'T': return T; case 'U': return U;
        case 'V': return V; case 'W': return W; case 'X': return X;
        case 'Y': return Y;
        case '0': return D0; case '1': return D1; case '2': return D2;
        case '3': return D3; case '4': return D4; case '5': return D5;
        case '6': return D6; case '7': return D7; case '8': return D8;
        case '9': return D9;
        case ':': return COLON; case '.': return DOT;
        case '-': return DASH;  case '/': return SLASH;
        default:  return SP;
    }
}

#endif /* FONT5X7_H */
